import kagglehub
import os
import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Dropout
from tensorflow.keras.callbacks import EarlyStopping
import matplotlib.pyplot as plt
import seaborn as sns

path = kagglehub.dataset_download("uditjain13/social-media-screen-time-and-mental-health-2026")
print("Path to dataset files:", path)

csv_file = os.path.join(path, "social_media_screentime_mental_health_2026.csv")
df = pd.read_csv(csv_file)

df = df.dropna()
X = df.drop(columns=['wellbeing_band'])
y = df['wellbeing_band']

X = pd.get_dummies(X, dtype=float)
y = pd.get_dummies(y, dtype=float)

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

# Define Early Stopping callback
early_stopping = EarlyStopping(monitor='val_loss', patience=5, restore_best_weights=True)

model = Sequential()
model.add(Dense(32, activation='relu', input_shape=(X_train.shape[1],)))
model.add(Dropout(0.3)) # Added Dropout layer
model.add(Dense(16, activation='relu'))
model.add(Dropout(0.3)) # Added Dropout layer
model.add(Dense(y.shape[1], activation='softmax'))
model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])

print("Starting training...")
# Train with validation split and early stopping
history = model.fit(X_train, y_train, epochs=100, batch_size=32, verbose=1, validation_split=0.2, callbacks=[early_stopping])

loss, accuracy = model.evaluate(X_test, y_test, verbose=0)

# Get the last epoch's training accuracy and loss
# Note: With EarlyStopping, these will be from the *best* epoch if restore_best_weights is True
final_train_accuracy = history.history['accuracy'][-1]
final_train_loss = history.history['loss'][-1]

print("\n" + "="*40)
print("  DEEP LEARNING MODEL RESULTS ")
print("="*40)
print(f"Features trained on: {X_train.shape[1]}")
print(f"Target categories:   {y.shape[1]}")
print("-" * 40)
print(f" Training Accuracy (last epoch): {final_train_accuracy * 100:.2f}%")
print(f" Training Loss (last epoch):    {final_train_loss:.4f}")
print("-" * 40)
print(f" Test Accuracy:    {accuracy * 100:.2f}%")
print(f" Test Loss:        {loss:.4f}")
print("="*40)

# Plotting accuracy and loss
plt.figure(figsize=(12, 5))
plt.subplot(1, 2, 1)
plt.plot(history.history['accuracy'], label='Train Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy') # Plot validation accuracy
plt.title('Model Accuracy')
plt.ylabel('Accuracy')
plt.xlabel('Epoch')
plt.legend(loc='upper left')

plt.subplot(1, 2, 2)
plt.plot(history.history['loss'], label='Train Loss')
plt.plot(history.history['val_loss'], label='Validation Loss') # Plot validation loss
plt.title('Model Loss')
plt.ylabel('Loss')
plt.xlabel('Epoch')
plt.legend(loc='upper left')

plt.tight_layout()
plt.show()

