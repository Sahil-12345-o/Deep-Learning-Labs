import kagglehub

path = kagglehub.dataset_download("sivm205/soybean-diseased-leaf-dataset")

print("Path to dataset files:", path)

import os

print(f"Contents of {path}:")
for root, dirs, files in os.walk(path):
    print(f'{os.path.basename(root)}/')
    for f in files:
        print(f'    {f}')

import os
from collections import defaultdict

image_counts = defaultdict(int)
class_names = []

data_dir = os.path.join(path, '1')

if not os.path.exists(data_dir):
    data_dir = path

for root, dirs, files in os.walk(data_dir):
    if root == data_dir:
        class_names = [d for d in dirs if not d.startswith('.')]

    for file in files:
        if file.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.bmp', '.tiff')):
            class_name = os.path.basename(root)
            image_counts[class_name] += 1

print("Class-wise image counts:")
for class_name, count in image_counts.items():
    print(f"  {class_name}: {count} images")

print(f"\nTotal number of classes: {len(class_names)}")
print(f"Detected class names: {class_names}")

import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator

img_height, img_width = 224, 224
batch_size = 32

data_directory = data_dir

datagen = ImageDataGenerator(
    rescale=1./255,
    validation_split=0.2
)

train_generator = datagen.flow_from_directory(
    data_directory,
    target_size=(img_height, img_width),
    batch_size=batch_size,
    class_mode='categorical',
    subset='training'
)

validation_generator = datagen.flow_from_directory(
    data_directory,
    target_size=(img_height, img_width),
    batch_size=batch_size,
    class_mode='categorical',
    subset='validation'
)

from tensorflow.keras import layers, models, Input

model = models.Sequential([
    Input(shape=(img_height, img_width, 3)),
    layers.Conv2D(
        32,
         (3, 3),
        activation='relu'
        ),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(
        64,
         (3, 3),
        activation='relu'),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(
        128,
        (3, 3),
        activation='relu'),
    layers.MaxPooling2D((2, 2)),
    layers.Flatten(),
    layers.Dense(512, activation='relu'),
    layers.Dropout(0.5),
    layers.Dense(len(class_names), activation='softmax')
])

model.compile(
    optimizer='adam',
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

model.summary()

import math

epochs = 10
history = model.fit(
    train_generator,
    steps_per_epoch=math.ceil(train_generator.samples / batch_size),
    epochs=epochs,
    validation_data=validation_generator,
    validation_steps=math.ceil(validation_generator.samples / batch_size)
)

print("Model training complete.")

import matplotlib.pyplot as plt

plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.plot(history.history['accuracy'])
plt.plot(history.history['val_accuracy'])
plt.title('Model Accuracy')
plt.ylabel('Accuracy')
plt.xlabel('Epoch')
plt.legend(['Train', 'Validation'], loc='upper left')

plt.subplot(1, 2, 2)
plt.plot(history.history['loss'])
plt.plot(history.history['val_loss'])
plt.title('Model Loss')
plt.ylabel('Loss')
plt.xlabel('Epoch')
plt.legend(['Train', 'Validation'], loc='upper left')

plt.tight_layout()
plt.show()

print('Class to index mapping:')
for class_name, index in train_generator.class_indices.items():
    print(f'{class_name}: {index}')